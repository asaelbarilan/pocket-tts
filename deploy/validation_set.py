"""Fixed Hebrew validation sentences, generated once per model and cached on disk.

`ValidationSet` renders every sentence of `eval_sentences_he.jsonl` with one randomly chosen
voice prompt, in a background thread, and stores the WAVs plus a `manifest.json` under
`<cache_root>/<cache_key>/`. The cache key comes from the model weights hash (and device kind),
so a new model never reuses audio generated by an old one. The manifest is rewritten after
every sentence, so a run that was cut short (e.g. a scaled-down instance) resumes where it
stopped, with the same voice. A finished cache is returned as is.

`start(force=True, voice=...)` throws the cached audio of the loaded model away and renders the
whole set again with the named voice instead of a random one (the preview page's "regenerate"
button). The new set replaces the old one as the model's cache.
"""

from __future__ import annotations

import hashlib
import json
import logging
import os
import random
import threading
import time
from collections.abc import Callable
from pathlib import Path

logger = logging.getLogger("hebrew_tts_server.validation")

SEED = 1234
MANIFEST = "manifest.json"

# (text, voice file name, seed) -> (wav bytes or None when the model ended speech at once,
# audio seconds, hit max length)
GenerateFn = Callable[[str, str, int], tuple[bytes | None, float, bool]]


def load_sentences(path: Path) -> tuple[list[dict], str]:
    raw = path.read_bytes()
    rows = [json.loads(line) for line in raw.decode("utf-8").splitlines() if line.strip()]
    return rows, hashlib.sha256(raw).hexdigest()


class ValidationBusy(RuntimeError):
    """A run is in progress; it is not interrupted by a forced regeneration."""


class ValidationSet:
    def __init__(
        self,
        sentences_path: Path,
        cache_root: Path,
        settings: dict,
        voices: Callable[[], list[str]],
        generate: GenerateFn,
        cache_key: Callable[[], str | None],
    ):
        self.sentences, sentences_sha = load_sentences(sentences_path)
        self.cache_root = cache_root
        self._voices = voices
        self._generate = generate
        self._cache_key = cache_key
        self.fingerprint = hashlib.sha256(
            json.dumps(
                {"sentences": sentences_sha, "settings": settings, "seed": SEED}, sort_keys=True
            ).encode()
        ).hexdigest()
        self._lock = threading.Lock()
        self._running = False
        self._error: str | None = None
        self._loaded_key: str | None = None
        self._manifest: dict | None = None
        self._forced_voice: str | None = None  # the voice of a forced regeneration, once

    # -- manifest -----------------------------------------------------------------------

    def _dir(self, key: str) -> Path:
        return self.cache_root / key

    def _ensure_loaded(self, key: str) -> None:
        """Read the manifest from disk once per cache key; a stale or missing one is dropped."""
        if self._loaded_key == key:
            return
        self._loaded_key = key
        self._manifest = None
        path = self._dir(key) / MANIFEST
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            return
        except (OSError, ValueError) as exc:
            logger.warning("ignoring unreadable validation manifest %s: %s", path, exc)
            return
        if data.get("fingerprint") != self.fingerprint:
            logger.info("validation manifest is for other sentences/settings; regenerating")
            return
        self._manifest = data

    def _save(self, key: str, manifest: dict) -> None:
        directory = self._dir(key)
        directory.mkdir(parents=True, exist_ok=True)
        tmp = directory / (MANIFEST + ".tmp")
        tmp.write_text(json.dumps(manifest, ensure_ascii=False, indent=1), encoding="utf-8")
        os.replace(tmp, directory / MANIFEST)

    def _finished_ids(self) -> set[str]:
        items = (self._manifest or {}).get("items", {})
        return {i for i, item in items.items() if item["status"] != "error"}

    # -- status -------------------------------------------------------------------------

    def status(self) -> dict:
        key = self._cache_key()
        if key is None:
            return {"state": "warming", "total": len(self.sentences), "done": 0, "items": []}
        with self._lock:
            try:
                self._ensure_loaded(key)
            except OSError as exc:
                self._error = f"cache not readable: {exc}"
            manifest = self._manifest or {}
            items = manifest.get("items", {})
            finished = self._finished_ids()
            if self._running:
                state = "running"
            elif self._error and len(finished) < len(self.sentences):
                state = "error"
            elif len(finished) >= len(self.sentences):
                state = "done"
            elif items:
                state = "partial"
            else:
                state = "none"
            ordered = [items[s["id"]] for s in self.sentences if s["id"] in items]
            return {
                "state": state,
                "total": len(self.sentences),
                "done": len(finished),
                "failed": sum(1 for i in items.values() if i["status"] == "error"),
                "voice": manifest.get("voice"),
                "model_sha256": key.split("-")[0],
                "error": self._error,
                "items": ordered,
            }

    def _discard(self, key: str) -> None:
        """Delete the cached audio and manifest of `key` (caller holds the lock, nothing runs)."""
        directory = self._dir(key)
        if directory.is_dir():
            for path in [*directory.glob("*.wav"), *directory.glob("*.tmp"), directory / MANIFEST]:
                path.unlink(missing_ok=True)
        self._manifest = None
        self._loaded_key = key

    def start(self, force: bool = False, voice: str | None = None) -> dict:
        """Start (or resume) the run for the loaded model.

        With `force`, the cached set is deleted and every sentence is rendered again with
        `voice`, a name from the voices list (required, so the result is reproducible with the
        voice the user chose). Raises ValueError for a missing or unknown voice and
        ValidationBusy while a run is in progress.
        """
        key = self._cache_key()
        if force and key is not None:
            with self._lock:
                if self._running:
                    raise ValidationBusy("the validation set is being generated; wait for it")
                if not voice or voice not in self._voices():
                    raise ValueError(f"unknown voice {voice!r}: choose one from the voice list")
                self._discard(key)
                self._error = None
                self._forced_voice = voice
        if key is not None:
            with self._lock:
                self._ensure_loaded(key)
                if not self._running and len(self._finished_ids()) < len(self.sentences):
                    self._running = True
                    self._error = None
                    threading.Thread(
                        target=self._run, args=(key,), name="validation-set", daemon=True
                    ).start()
        return self.status()

    def audio_path(self, item_id: str) -> Path | None:
        key = self._cache_key()
        if key is None:
            return None
        with self._lock:
            self._ensure_loaded(key)
            item = (self._manifest or {}).get("items", {}).get(item_id)
        if not item or not item.get("file"):
            return None
        return self._dir(key) / item["file"]

    # -- generation ---------------------------------------------------------------------

    def _run(self, key: str) -> None:
        try:
            with self._lock:
                manifest = self._manifest
                if manifest is None:
                    voices = sorted(self._voices())
                    if not voices:
                        raise RuntimeError("no voice prompts available")
                    chosen, self._forced_voice = self._forced_voice, None
                    manifest = {
                        "fingerprint": self.fingerprint,
                        "model_sha256": key.split("-")[0],
                        "voice": chosen or random.choice(voices),
                        "seed": SEED,
                        "items": {},
                    }
                    self._manifest = manifest
                done = self._finished_ids()
            voice = manifest["voice"]
            logger.info("validation set: %d sentences, voice %s", len(self.sentences), voice)
            directory = self._dir(key)
            directory.mkdir(parents=True, exist_ok=True)

            for sentence in self.sentences:
                if sentence["id"] in done:
                    continue
                item = {k: sentence[k] for k in ("id", "category", "text", "note") if k in sentence}
                started = time.perf_counter()
                try:
                    wav, seconds, hit_max = self._generate(sentence["text"], voice, SEED)
                    elapsed = time.perf_counter() - started
                    item.update(
                        status="ok" if wav is not None else "eos",
                        file=None,
                        audio_seconds=round(seconds, 2),
                        generation_seconds=round(elapsed, 2),
                        hit_max_length=hit_max,
                    )
                    if wav is not None:
                        name = f"{sentence['id']}.wav"
                        tmp = directory / (name + ".tmp")
                        tmp.write_bytes(wav)
                        os.replace(tmp, directory / name)
                        item["file"] = name
                except Exception as exc:
                    logger.exception("validation sentence %s failed", sentence["id"])
                    item.update(status="error", error=f"{type(exc).__name__}: {exc}")
                with self._lock:
                    manifest["items"][sentence["id"]] = item
                    self._save(key, manifest)
            logger.info("validation set finished")
        except Exception as exc:
            logger.exception("validation set failed")
            self._error = f"{type(exc).__name__}: {exc}"
        finally:
            with self._lock:
                self._running = False
