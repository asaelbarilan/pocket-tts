"""Fixed Hebrew validation sentences, generated once per model and cached on disk.

`ValidationSet` renders every sentence of `eval_sentences_he.jsonl` with one randomly chosen
voice prompt, in a background thread, and stores the WAVs plus a `manifest.json` under
`<cache_root>/<cache_key>/`. The cache key comes from the model weights hash (and device kind),
so a new model never reuses audio generated by an old one. The manifest is rewritten after
every sentence, so a run that was cut short (e.g. a scaled-down instance) resumes where it
stopped, with the same voice. A finished cache is returned as is.

`start(force=True, voice=...)` throws the cached audio of the loaded model away and renders the
whole set again with the named voice instead of a random one (the preview page's "regenerate"
button). The new set replaces the old one as the model's cache.

Past runs: every other folder under the cache root whose manifest is for the same sentences
(`past_runs`) is a validation set an earlier model rendered, so the preview page can put their
audio next to the loaded model's. Nothing is registered anywhere: the cache folders are the list.
A run is named by its model's run name when the model store knows it, else by its cache folder,
else by the date its manifest was last written.
"""

from __future__ import annotations

import hashlib
import inspect
import json
import logging
import os
import threading
import time
from collections.abc import Callable
from pathlib import Path

logger = logging.getLogger("hebrew_tts_server.validation")

SEED = 1234
MANIFEST = "manifest.json"

# (text, voice file name, seed[, settings]) -> (wav bytes or None when the model ended speech at
# once, audio seconds, hit max length)
GenerateFn = Callable[..., tuple[bytes | None, float, bool]]


def load_sentences(path: Path) -> tuple[list[dict], str]:
    raw = path.read_bytes()
    rows = [json.loads(line) for line in raw.decode("utf-8").splitlines() if line.strip()]
    return rows, hashlib.sha256(raw).hexdigest()


class ValidationBusy(RuntimeError):
    """A run is in progress; it is not interrupted by a forced regeneration."""


class ValidationSet:
    def __init__(
        self,
        sentences_path: Path,
        cache_root: Path,
        settings: dict,
        voices: Callable[[], list[str]],
        generate: GenerateFn,
        cache_key: Callable[[], str | None],
        describe: Callable[[str], dict] | None = None,
    ):
        self.sentences, self._sentences_sha = load_sentences(sentences_path)
        self.cache_root = cache_root
        self._default_settings = dict(settings)
        self._voices = voices
        self._generate = generate
        self._gen_takes_settings = len(inspect.signature(generate).parameters) >= 4
        self._cache_key = cache_key
        # model sha256 prefix -> {"run", "note", "created"} from the model store, when known
        self._describe = describe
        self.fingerprint = hashlib.sha256(
            json.dumps(
                {"sentences": self._sentences_sha, "settings": settings, "seed": SEED},
                sort_keys=True,
            ).encode()
        ).hexdigest()
        self._lock = threading.Lock()
        self._running = False
        self._error: str | None = None
        self._loaded_key: str | None = None
        self._manifest: dict | None = None
        self._forced_voice: str | None = None  # the voice of a new or forced run, once
        self._pending_settings: dict | None = None
        self._pending_seed: int | None = None

    # -- manifest -----------------------------------------------------------------------

    def _dir(self, key: str) -> Path:
        return self.cache_root / key

    def _ensure_loaded(self, key: str) -> None:
        """Read the manifest from disk once per cache key; a stale or missing one is dropped."""
        if self._loaded_key == key:
            return
        self._loaded_key = key
        self._manifest = None
        path = self._dir(key) / MANIFEST
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            return
        except (OSError, ValueError) as exc:
            logger.warning("ignoring unreadable validation manifest %s: %s", path, exc)
            return
        if not self._same_set(data):
            logger.info("validation manifest is for other sentences/settings; regenerating")
            return
        self._manifest = data

    def _same_set(self, data: dict) -> bool:
        """Whether a manifest was rendered from these sentences (older manifests have only the
        fingerprint, which also covers the sampling defaults of their time)."""
        if "sentences_sha" in data:
            return data["sentences_sha"] == self._sentences_sha
        return data.get("fingerprint") == self.fingerprint

    def _save(self, key: str, manifest: dict) -> None:
        directory = self._dir(key)
        directory.mkdir(parents=True, exist_ok=True)
        tmp = directory / (MANIFEST + ".tmp")
        tmp.write_text(json.dumps(manifest, ensure_ascii=False, indent=1), encoding="utf-8")
        os.replace(tmp, directory / MANIFEST)

    def _finished_ids(self) -> set[str]:
        items = (self._manifest or {}).get("items", {})
        return {i for i, item in items.items() if item["status"] != "error"}

    # -- status -------------------------------------------------------------------------

    def status(self) -> dict:
        key = self._cache_key()
        if key is None:
            return {"state": "warming", "total": len(self.sentences), "done": 0, "items": []}
        with self._lock:
            try:
                self._ensure_loaded(key)
            except OSError as exc:
                self._error = f"cache not readable: {exc}"
            manifest = self._manifest or {}
            items = manifest.get("items", {})
            finished = self._finished_ids()
            if self._running:
                state = "running"
            elif self._error and len(finished) < len(self.sentences):
                state = "error"
            elif len(finished) >= len(self.sentences):
                state = "done"
            elif items:
                state = "partial"
            else:
                state = "none"
            ordered = [items[s["id"]] for s in self.sentences if s["id"] in items]
            return {
                "state": state,
                "total": len(self.sentences),
                "done": len(finished),
                "failed": sum(1 for i in items.values() if i["status"] == "error"),
                "voice": manifest.get("voice"),
                "settings": manifest.get("settings"),
                "seed": manifest.get("seed"),
                "model_sha256": key.split("-")[0],
                "error": self._error,
                "items": ordered,
            }

    # -- past runs ----------------------------------------------------------------------

    def _read_run(self, run_id: str) -> tuple[dict, float] | None:
        """(manifest, last write time) of another cache folder of the same sentences, or None."""
        if not run_id or run_id in (".", "..") or Path(run_id).name != run_id:
            return None
        path = self._dir(run_id) / MANIFEST
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            mtime = path.stat().st_mtime
        except (OSError, ValueError):
            return None
        if not isinstance(data, dict) or not self._same_set(data):
            return None
        return data, mtime

    def _summarize(self, run_id: str, data: dict, mtime: float) -> dict:
        sha = str(data.get("model_sha256") or run_id.split("-")[0])
        meta = {}
        if self._describe is not None:
            try:
                meta = self._describe(sha) or {}
            except Exception:
                logger.exception("could not describe model %s", sha)
        run = data.get("model_run") or meta.get("run")
        date = time.strftime("%Y-%m-%d %H:%M UTC", time.gmtime(mtime))
        items = data.get("items", {})
        done = sum(1 for i in items.values() if i.get("status") != "error")
        return {
            "id": run_id,
            "label": run or run_id or date,
            "run": run,
            "folder": run_id,
            "date": date,
            "mtime": int(mtime),
            "model_sha256": sha,
            "device": run_id.rsplit("-", 1)[1] if "-" in run_id else None,
            "note": meta.get("note"),
            "voice": data.get("voice"),
            "seed": data.get("seed"),
            "settings": data.get("settings"),
            "done": done,
            "total": len(self.sentences),
            "state": "done" if done >= len(self.sentences) else "partial",
        }

    def past_runs(self) -> list[dict]:
        """The cached sets of other models (and device kinds) for these sentences, newest first."""
        current = self._cache_key()
        try:
            folders = [p.name for p in self.cache_root.iterdir() if p.is_dir()]
        except OSError:
            return []
        runs = []
        for name in folders:
            if name == current:
                continue
            found = self._read_run(name)
            if found is not None:
                runs.append(self._summarize(name, *found))
        runs.sort(key=lambda r: r["mtime"], reverse=True)
        return runs

    def run_detail(self, run_id: str) -> dict | None:
        """A past run with its items in sentence order, or None when there is no such run."""
        if run_id == self._cache_key():
            return None
        found = self._read_run(run_id)
        if found is None:
            return None
        data, mtime = found
        items = data.get("items", {})
        return {
            **self._summarize(run_id, data, mtime),
            "items": [items[s["id"]] for s in self.sentences if s["id"] in items],
        }

    def run_audio_path(self, run_id: str, item_id: str) -> Path | None:
        found = None if run_id == self._cache_key() else self._read_run(run_id)
        if found is None:
            return None
        item = found[0].get("items", {}).get(item_id)
        name = item.get("file") if item else None
        if not name or Path(name).name != name:
            return None
        return self._dir(run_id) / name

    def sentence_rows(self) -> list[dict]:
        return [
            {k: s[k] for k in ("id", "category", "text", "note") if k in s} for s in self.sentences
        ]

    def _discard(self, key: str) -> None:
        """Delete the cached audio and manifest of `key` (caller holds the lock, nothing runs)."""
        directory = self._dir(key)
        if directory.is_dir():
            for path in [*directory.glob("*.wav"), *directory.glob("*.tmp"), directory / MANIFEST]:
                path.unlink(missing_ok=True)
        self._manifest = None
        self._loaded_key = key

    def start(
        self,
        force: bool = False,
        voice: str | None = None,
        settings: dict | None = None,
        seed: int | None = None,
    ) -> dict:
        """Start (or resume) the run for the loaded model.

        With `force`, the cached set is deleted and every sentence is rendered again with
        `voice` and `settings`. When no cached set exists yet, an initial `start` also uses the
        provided `voice` and `settings` (falling back to the first voice and default settings
        when omitted). Raises ValueError for a missing (on force) or unknown voice and
        ValidationBusy while a run is in progress.
        """
        key = self._cache_key()
        if force and key is not None:
            with self._lock:
                if self._running:
                    raise ValidationBusy("the validation set is being generated; wait for it")
                if not voice or voice not in self._voices():
                    raise ValueError(f"unknown voice {voice!r}: choose one from the voice list")
                self._discard(key)
                self._error = None
                self._forced_voice = voice
                self._pending_settings = {**self._default_settings, **(settings or {})}
                self._pending_seed = seed if seed is not None else SEED
        elif key is not None:
            with self._lock:
                if voice:
                    if voice not in self._voices():
                        raise ValueError(f"unknown voice {voice!r}: choose one from the voice list")
                    self._forced_voice = voice
                if settings is not None:
                    self._pending_settings = {**self._default_settings, **settings}
                if seed is not None:
                    self._pending_seed = seed
        if key is not None:
            with self._lock:
                self._ensure_loaded(key)
                if not self._running and len(self._finished_ids()) < len(self.sentences):
                    self._running = True
                    self._error = None
                    threading.Thread(
                        target=self._run, args=(key,), name="validation-set", daemon=True
                    ).start()
        return self.status()

    def audio_path(self, item_id: str) -> Path | None:
        key = self._cache_key()
        if key is None:
            return None
        with self._lock:
            self._ensure_loaded(key)
            item = (self._manifest or {}).get("items", {}).get(item_id)
        if not item or not item.get("file"):
            return None
        return self._dir(key) / item["file"]

    # -- generation ---------------------------------------------------------------------

    def _run(self, key: str) -> None:
        try:
            with self._lock:
                manifest = self._manifest
                if manifest is None:
                    voices = sorted(self._voices())
                    if not voices:
                        raise RuntimeError("no voice prompts available")
                    chosen, self._forced_voice = self._forced_voice, None
                    run_settings = self._pending_settings or dict(self._default_settings)
                    self._pending_settings = None
                    run_seed = self._pending_seed if self._pending_seed is not None else SEED
                    self._pending_seed = None
                    manifest = {
                        "fingerprint": self.fingerprint,
                        "sentences_sha": self._sentences_sha,
                        "model_sha256": key.split("-")[0],
                        "voice": chosen or voices[0],
                        "settings": run_settings,
                        "seed": run_seed,
                        "items": {},
                    }
                    self._manifest = manifest
                else:
                    self._forced_voice = None
                    self._pending_settings = None
                    self._pending_seed = None
                done = self._finished_ids()
            voice = manifest["voice"]
            run_settings = manifest.get("settings") or dict(self._default_settings)
            run_seed = manifest.get("seed", SEED)
            logger.info(
                "validation set: %d sentences, voice %s, settings %s, seed %s",
                len(self.sentences),
                voice,
                run_settings,
                run_seed,
            )
            directory = self._dir(key)
            directory.mkdir(parents=True, exist_ok=True)

            for sentence in self.sentences:
                if sentence["id"] in done:
                    continue
                item = {k: sentence[k] for k in ("id", "category", "text", "note") if k in sentence}
                started = time.perf_counter()
                try:
                    if self._gen_takes_settings:
                        wav, seconds, hit_max = self._generate(
                            sentence["text"], voice, run_seed, run_settings
                        )
                    else:
                        wav, seconds, hit_max = self._generate(sentence["text"], voice, run_seed)
                    elapsed = time.perf_counter() - started
                    item.update(
                        status="ok" if wav is not None else "eos",
                        file=None,
                        audio_seconds=round(seconds, 2),
                        generation_seconds=round(elapsed, 2),
                        hit_max_length=hit_max,
                    )
                    if wav is not None:
                        name = f"{sentence['id']}.wav"
                        tmp = directory / (name + ".tmp")
                        tmp.write_bytes(wav)
                        os.replace(tmp, directory / name)
                        item["file"] = name
                except Exception as exc:
                    logger.exception("validation sentence %s failed", sentence["id"])
                    item.update(status="error", error=f"{type(exc).__name__}: {exc}")
                with self._lock:
                    manifest["items"][sentence["id"]] = item
                    self._save(key, manifest)
            logger.info("validation set finished")
        except Exception as exc:
            logger.exception("validation set failed")
            self._error = f"{type(exc).__name__}: {exc}"
        finally:
            with self._lock:
                self._running = False
